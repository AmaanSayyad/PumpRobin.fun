#!/usr/bin/env node
/**
 * Generates a fresh deployer EOA and writes the key straight into .env, which
 * is gitignored. The key is never printed — only the address, which is what
 * you need in order to fund it.
 *
 *   node scripts/new-deployer-wallet.mjs
 *
 * Refuses to overwrite an existing DEPLOYER_PRIVATE_KEY unless --force.
 */
import fs from "node:fs";
import path from "node:path";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";

const ENV = path.join(process.cwd(), ".env");
const force = process.argv.includes("--force");

let env = fs.existsSync(ENV) ? fs.readFileSync(ENV, "utf8") : "";
const existing = env.match(/^DEPLOYER_PRIVATE_KEY=(.+)$/m);

if (existing && existing[1].trim() && !force) {
  const account = privateKeyToAccount(existing[1].trim());
  console.log("A deployer wallet already exists in .env — leaving it alone.");
  console.log(`  address ${account.address}`);
  console.log("  (re-run with --force to replace it)");
  process.exit(0);
}

const privateKey = generatePrivateKey();
const account = privateKeyToAccount(privateKey);

const line = `DEPLOYER_PRIVATE_KEY=${privateKey}`;
env = existing
  ? env.replace(/^DEPLOYER_PRIVATE_KEY=.*$/m, line)
  : `${env.replace(/\s*$/, "")}\n\n# Deploys the contracts. Generated by scripts/new-deployer-wallet.mjs.\n# This address permanently owns the factory — treat it as a production key.\n${line}\n`;

fs.writeFileSync(ENV, env, { mode: 0o600 });

console.log("Deployer wallet written to .env (gitignored).\n");
console.log(`  address  ${account.address}\n`);
console.log("Fund that address, then run:");
console.log("  node scripts/compile.mjs");
console.log("  node scripts/deploy-v4.mjs");
